export type CountryCode = (typeof COUNTRY_CODES)[number]

const COUNTRY_CODE_SET: ReadonlySet<string> = new Set(COUNTRY_CODES)

export type CountryCodeCheck = { valid: true; value: CountryCode | null } | { valid: false; error: string }

/**
 * Validates an optional country code: trims it, ignores case and checks it against ISO 3166-1 alpha-2.
 * Missing or blank values are valid and normalize to null; valid values normalize to uppercase.
 */
export const checkCountryCode = (raw: unknown): CountryCodeCheck => {
  if (raw === undefined || raw === null) {
    return { valid: true, value: null }
  }
  if (typeof raw !== 'string') {
    return {
      valid: false,
      error: `Invalid country code "${String(raw)}": must be an ISO 3166-1 alpha-2 code`,
    }
  }

  const trimmed = raw.trim()
  if (!trimmed) {
    return { valid: true, value: null }
  }

  const normalized = trimmed.toUpperCase()
  if (!COUNTRY_CODE_SET.has(normalized)) {
    return { valid: false, error: `Invalid country code "${trimmed}": must be an ISO 3166-1 alpha-2 code` }
  }

  return { valid: true, value: normalized as CountryCode }
}
